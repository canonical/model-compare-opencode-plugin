// tests/conformance/vendor-contract.test.ts
// The vendored script's behavioral contract at the pinned tag (design §11):
// the version banner names the pinned version, the published overall scores
// equal the weight-space recomputation within rounding, the published
// rankings cover exactly the candidate id set, and argument errors exit 2
// (§9 — exit 2 is a usage failure, never "no candidates"). Every check runs
// offline: python3 spawns the vendored file only, in the local source's
// minimal environment, with no catalog fetch.
import { spawn } from "node:child_process"
import { readFileSync } from "node:fs"
import { validateCatalog } from "../../src/core/catalog"
import { effectiveWeights, overallScore } from "../../src/core/rank"
import type { Catalog, Priority } from "../../src/core/types"
import { scriptEnv } from "../../src/sources/local"

const VENDOR_SCRIPT = "vendor/model_compare.py"
const UPSTREAM_META = "vendor/UPSTREAM.json"
// Recorded at v0.3.0. v0.3.1 changed only the VERSION string in the script and
// kept the catalog contract (schema v2), so this stays the contract fixture.
const TAGGED_FIXTURE = "fixtures/catalog-v0.3.0.json"
const PRIORITIES: Priority[] = ["balanced", "price", "quality"]

const meta = JSON.parse(readFileSync(UPSTREAM_META, "utf8")) as { tag: string }

// The tagged fixture, validated once and shared: the plugin's own Catalog
// projection of upstream's published document.
const raw = JSON.parse(readFileSync(TAGGED_FIXTURE, "utf8"))
const validated = validateCatalog(raw)
if (!validated.ok) throw new Error(`fixture no longer validates: ${validated.reason}`)
const CATALOG: Catalog = validated.catalog

// Runs the vendored script through real python3 with the local source's
// minimal environment (the HOME/PATH allowlist — no API keys, no proxies)
// and resolves with the exit code plus the captured streams.
function runVendorScript(
  args: string[],
): Promise<{ code: number | null; stdout: string; stderr: string }> {
  return new Promise((resolve, reject) => {
    const child = spawn("python3", [VENDOR_SCRIPT, ...args], { env: scriptEnv() })
    let stdout = ""
    let stderr = ""
    child.stdout?.on("data", (chunk: Buffer) => {
      stdout += chunk
    })
    child.stderr?.on("data", (chunk: Buffer) => {
      stderr += chunk
    })
    child.on("error", reject)
    child.on("close", (code) => resolve({ code, stdout, stderr }))
  })
}

test("--version's last whitespace-separated token is the pinned tag without the leading v", async () => {
  const { code, stdout } = await runVendorScript(["--version"])
  expect(code).toBe(0)
  const tokens = stdout.trim().split(/\s+/)
  expect(tokens[tokens.length - 1], `--version printed: ${stdout.trim()}`).toBe(
    meta.tag.replace(/^v/, ""),
  )
})

// Both fixtures: the recorded catalog and the quality-blind one (generated by
// scripts/make-no-quality-fixture.py with the vendored script's own functions,
// so its scores.overall is consistent with its renormalized weights).
const NO_QUALITY_FIXTURE = "fixtures/catalog-no-quality.json"

test.each([
  ["the recorded catalog", CATALOG],
  [
    "the no-quality catalog",
    (() => {
      const v = validateCatalog(JSON.parse(readFileSync(NO_QUALITY_FIXTURE, "utf8")))
      if (!v.ok) throw new Error(`no-quality fixture no longer validates: ${v.reason}`)
      return v.catalog
    })(),
  ],
])("every published overall score is the weight-space recomputation within 0.005 — %s", (_name, catalog) => {
  const mismatches: string[] = []
  for (const p of PRIORITIES) {
    // No override: the published weights for this priority with missing keys
    // counted as 0 — the same derivation upstream applies (design §5, §6).
    const w = effectiveWeights(catalog, p, undefined).weights
    for (const model of catalog.models) {
      const recomputed = overallScore(model, w)
      const diff = Math.abs(recomputed - model.scores.overall[p])
      if (diff > 0.005) {
        mismatches.push(`${p} ${model.id}: |${recomputed} − ${model.scores.overall[p]}| = ${diff}`)
      }
    }
  }
  expect(mismatches, "published overall diverges from the recomputation").toEqual([])
})

test("each published ranking covers exactly the model id set — no missing, no extra ids", () => {
  const ids = new Set(CATALOG.models.map((m) => m.id))
  expect(Object.keys(CATALOG.rankings).length, "the fixture publishes rankings").toBeGreaterThan(0)
  for (const p of PRIORITIES) {
    const ranking = CATALOG.rankings[p]
    if (ranking === undefined) continue // rankings are optional per §5
    expect(new Set(ranking), `rankings.${p} vs models`).toEqual(ids)
  }
})

test("an unknown flag exits 2 with a non-empty stderr — §9: exit 2 is a usage failure, never 'no candidates'", async () => {
  const { code, stderr } = await runVendorScript(["--no-such-flag"])
  expect(code).toBe(2)
  expect(stderr.trim().length, `stderr was: ${stderr.trim()}`).toBeGreaterThan(0)
})